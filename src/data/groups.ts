export const teams: Team[] = Object.values(groups).flatMap((list) =>
  list.map((team) => {
    const actualRoster = actualRosters[team.id];
    if (!actualRoster) {
      throw new Error(`Missing roster data for ${team.id}`);
    }

    return {
      ...team,
      roster: actualRoster.roster,
      xi: actualRoster.xi,
      rosterSource: actualRoster.source,
      rosterFetchedAt: actualRoster.fetchedAt,
    };
  }),
);

export const teamMap = Object.fromEntries(teams.map((team) => [team.id, team]));
export const groupKeys = Object.keys(groups);
